/**
 * วันที่บนเอกสารต้องเป็นวันที่ตามเวลาไทยเสมอ
 *
 * เซิร์ฟเวอร์ส่วนใหญ่ตั้งเขตเวลาเป็น UTC ถ้าโปรแกรมใช้เวลาเครื่อง
 * ใบที่ออกตอนตีหนึ่งครึ่งจะลงวันที่ของเมื่อวาน — วันที่ผิดบนใบกำกับภาษี
 */
import { describe, expect, it } from 'vitest';
import { isoInShopTz, SHOP_TZ, today } from '../src/date.js';

describe('วันที่ตามเวลาไทย', () => {
  it('ตีหนึ่งครึ่งเวลาไทยยังเป็นวันเดียวกัน ไม่ถอยไปเมื่อวานแบบเวลา UTC', () => {
    /* 2026-08-31 18:30 UTC = 2026-09-01 01:30 ตามเวลาไทย */
    const d = new Date('2026-08-31T18:30:00Z');
    expect(isoInShopTz(d)).toBe('2026-09-01');
  });

  it('หกโมงครึ่งเย็นเวลาไทยยังไม่ข้ามวัน', () => {
    /* 2026-09-01 11:30 UTC = 2026-09-01 18:30 ตามเวลาไทย */
    expect(isoInShopTz(new Date('2026-09-01T11:30:00Z'))).toBe('2026-09-01');
  });

  it('เที่ยงคืนตรงเวลาไทยคือวันใหม่', () => {
    expect(isoInShopTz(new Date('2026-08-31T17:00:00Z'))).toBe('2026-09-01');
    expect(isoInShopTz(new Date('2026-08-31T16:59:59Z'))).toBe('2026-08-31');
  });

  it('ข้ามปีถูกต้อง', () => {
    expect(isoInShopTz(new Date('2026-12-31T17:00:00Z'))).toBe('2027-01-01');
  });

  it('today() คืนรูปแบบ YYYY-MM-DD', () => {
    expect(today()).toMatch(/^\d{4}-\d{2}-\d{2}$/);
    expect(SHOP_TZ).toBe('Asia/Bangkok');
  });
});
