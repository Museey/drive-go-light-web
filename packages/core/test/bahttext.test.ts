/** จำนวนเงินเป็นตัวหนังสือ — เคสภาษาไทยที่คนมักทำพลาด */
import { describe, expect, it } from 'vitest';
import { bahttext } from '../src/index.js';

describe('bahttext', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [10, 'สิบบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [20, 'ยี่สิบบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [100, 'หนึ่งร้อยบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [1000000, 'หนึ่งล้านบาทถ้วน'],
    [1000001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
    [3638, 'สามพันหกร้อยสามสิบแปดบาทถ้วน'],
  ])('%s → %s', (n, expected) => {
    expect(bahttext(n)).toBe(expected);
  });

  it('มีสตางค์', () => {
    expect(bahttext(3638.25)).toBe('สามพันหกร้อยสามสิบแปดบาทยี่สิบห้าสตางค์');
    expect(bahttext(0.5)).toBe('ศูนย์บาทห้าสิบสตางค์');
    expect(bahttext(1.01)).toBe('หนึ่งบาทหนึ่งสตางค์');
  });

  it('ปัดเป็นสตางค์ก่อนแปลงเสมอ', () => {
    expect(bahttext(1.006)).toBe('หนึ่งบาทหนึ่งสตางค์');
    expect(bahttext(1.004)).toBe('หนึ่งบาทถ้วน');
  });

  /**
   * ข้อจำกัดที่รู้อยู่ ไม่ใช่บั๊กที่เพิ่งเกิด — ของเดิมก็เป็นแบบนี้
   *
   * `Math.round(1.005 * 100) / 100` ได้ 1.00 ไม่ใช่ 1.01 เพราะ 1.005 เก็บใน float
   * ได้เป็น 1.00499999... การคูณ 100 จึงได้ 100.49999999999999 แล้วปัดลง
   *
   * ในทางปฏิบัติแทบไม่มีผล เพราะยอดเงินจริงไม่ค่อยลงตัวที่ครึ่งสตางค์พอดี
   * แต่บันทึกไว้ให้รู้ตัว — ถ้าวันหนึ่งจะเปลี่ยนไปใช้ decimal ทั้งระบบ
   * ค่าที่ได้จะต่างจากเอกสารเก่าตรงนี้ และต้องตัดสินใจว่าจะให้เอกสารเก่าเปลี่ยนตามหรือไม่
   */
  it('เศษครึ่งสตางค์พอดีปัดลง (ข้อจำกัดของ float ที่ยกมาจากของเดิม)', () => {
    expect(bahttext(1.005)).toBe('หนึ่งบาทถ้วน');
  });

  it('รับข้อความที่มีคอมมาได้', () => {
    expect(bahttext('1,250.50')).toBe('หนึ่งพันสองร้อยห้าสิบบาทห้าสิบสตางค์');
  });
});
