import Link from 'next/link';

/**
 * ป้ายทะเบียนรถ — หน้าตาเดียวกันทุกหน้า (26 พ.ย. 2569 — ผู้ใช้ขอให้ทะเบียนเด่นและอ่านง่ายกว่าเดิม)
 *
 * อู่จำลูกค้าด้วยทะเบียนรถมากกว่าชื่อ: เปิดเอกสารใหม่ ค้นหา และไล่รายการ ล้วนเริ่มจากทะเบียน
 * เดิมทะเบียนเป็นตัวอักษรเทาขนาดเล็กใต้ชื่อลูกค้า กวาดตาหาไม่เจอ
 * ตอนนี้เป็นป้ายกรอบเข้ม พื้นขาว ตัวหนา แบบป้ายทะเบียนจริง — เห็นรูปทรงก็รู้ว่าเป็นทะเบียนก่อนอ่านตัวอักษร
 *
 * ไม่ใช้ฟอนต์ความกว้างคงที่: ฟอนต์นั้นไม่มีอักษรไทย เบราว์เซอร์สลับฟอนต์กลางป้ายแล้วตัวอักษรสูงต่ำไม่เท่ากัน
 * สไตล์อยู่ที่ globals.css (.plate-badge)
 */
export function Plate({ value, href, size, title, hit }: {
  value: string | null | undefined;
  /** มีลิงก์ = กดแล้วไปประวัติของรถคันนั้น */
  href?: string;
  /** lg = หัวข้อของรถบนหน้าออกเอกสารและการ์ดผลค้นหา */
  size?: 'lg';
  title?: string;
  /** ทะเบียนนี้ตรงกับคำที่กำลังค้น — พื้นเหลืองให้เห็นว่าผลค้นหาขึ้นมาเพราะคันไหน */
  hit?: boolean;
}) {
  const text = (value ?? '').trim();
  if (!text) return null;
  /* plate-link คงไว้กับป้ายที่กดได้ — เทสต์หน้าจอและสไตล์เดิมอ้างชื่อนี้ */
  const cls = ['plate-badge', size === 'lg' ? 'lg' : '', hit ? 'hit' : '', href ? 'plate-link' : ''].filter(Boolean).join(' ');
  return href
    ? <Link href={href} className={cls} title={title ?? 'ดูประวัติของรถคันนี้'}>{text}</Link>
    : <span className={cls} title={title}>{text}</span>;
}
