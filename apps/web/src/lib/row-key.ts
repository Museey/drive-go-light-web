/**
 * กุญแจประจำบรรทัดของตารางรายการในตัวแก้เอกสาร (ใบขาย · ใบซื้อ)
 *
 * เดิมแถววาดด้วย `key={ลำดับ}` — แต่ละแถวมีสถานะของตัวเอง (คำที่กำลังค้น ผลค้นหาที่หล่นใต้แถว
 * ข้อความที่พิมพ์ค้างในช่องตัวเลข) React ผูกสถานะนั้นกับ**ลำดับ** ไม่ใช่กับบรรทัด
 * ลบบรรทัดที่ 2 แล้วคำค้นของบรรทัดที่ 2 จึงไปโผล่บนของที่เลื่อนขึ้นมาจากบรรทัดที่ 3
 * กดเลือกผลค้นหานั้นคือเขียนทับสินค้าผิดบรรทัด (ตรวจ 24 พ.ย. 2569)
 *
 * กุญแจติดไปกับตัวบรรทัดในสถานะของหน้าจอ รอดการแก้ช่องต่าง ๆ เพราะทุกทางแก้ใช้ `{ ...บรรทัด, ... }`
 * และ**ไม่ถูกส่งไปบันทึก** — ตัดออกด้วย stripRowKeys() ก่อนประกอบ payload
 *
 * ไม่มี React อยู่ในไฟล์นี้ ชุดทดสอบเรียกได้ตรง ๆ
 */

export type Keyed<T> = T & { _k?: string };

let seq = 0;

/**
 * เติมกุญแจให้บรรทัดที่ยังไม่มี — บรรทัดที่มีแล้วไม่ถูกแตะ
 * คืนอาเรย์ตัวเดิมเมื่อไม่มีอะไรต้องเติม ผู้เรียกจึงใช้เทียบ === เพื่อไม่วาดใหม่โดยไม่จำเป็นได้
 */
export function keyRows<T extends object>(items: T[]): T[] {
  if (items.every((it) => (it as Keyed<T>)._k)) return items;
  return items.map((it) => ((it as Keyed<T>)._k ? it : { ...it, _k: `r${++seq}` }));
}

/** กุญแจของบรรทัด — ถอยไปใช้ลำดับถ้าบรรทัดยังไม่ผ่าน keyRows() (ไม่ควรเกิด แต่ต้องไม่พัง) */
export function rowKey(item: object, index: number): string {
  return (item as Keyed<object>)._k ?? `i${index}`;
}

/** ตัดกุญแจออกก่อนส่งไปบันทึก — เซิร์ฟเวอร์ไม่ควรเห็นของที่มีไว้ให้หน้าจอใช้ */
export function stripRowKeys<T extends object>(items: T[]): T[] {
  return items.map((it) => {
    if (!('_k' in it)) return it;
    const { _k: _drop, ...rest } = it as Keyed<T>;
    void _drop;
    return rest as T;
  });
}

/**
 * ครอบตัวตั้งสถานะของเอกสาร ให้ทุกบรรทัดมีกุญแจเสมอ ไม่ว่าจะมาจากทางไหน
 * (เพิ่มบรรทัด ยิงบาร์โค้ด ดึงรายการจากใบต้นทาง เติมบรรทัดว่างหลังลบ)
 */
export function keyedDoc<D extends { items: object[] }>(doc: D): D {
  const items = keyRows(doc.items);
  return items === doc.items ? doc : { ...doc, items };
}
