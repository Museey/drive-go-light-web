/**
 * เอกสารในถังขยะชนิดไหนกู้คืนได้ — ใช้ร่วมกันทั้ง trash-core (ฝั่งเขียน) และหน้าถังขยะ (ปุ่มที่แสดง)
 *
 * **กู้คืนได้เฉพาะเอกสารที่ไม่ได้ออกไปถึงลูกค้าหรือกรมสรรพากร**
 * ใบเสนอราคา ใบวางบิล ใบซื้อ และค่าใช้จ่าย กู้คืนได้
 * ใบส่งมอบ ใบกำกับภาษี และใบเสร็จที่ยกเลิกแล้ว กู้คืนไม่ได้ ต้องคัดลอกเป็นใบใหม่
 * เพราะอาจส่งให้ลูกค้าหรือยื่นภาษีไปแล้ว การพลิกกลับเป็นใบปกติจะทำให้ยอดขาย ภาษีขาย
 * และเอกสารที่ลูกค้าถืออยู่ไม่ตรงกัน
 *
 * ตัดสินใจร่วมกับเจ้าของกิจการ 14 ก.ย. 2569 — กติกาเดียวกับ 018_unvoid และรุ่น 6.4
 * (ถังขยะในชุดแก้ 13 ก.ย. เดิมให้กู้คืนใบเสร็จได้)
 */
export const RESTORABLE_KINDS: ReadonlySet<string> = new Set(['QT', 'BN', 'PO', 'EX']);

export function isRestorable(kind: string): boolean {
  return RESTORABLE_KINDS.has(kind);
}

/** เอกสารรายรับที่กู้คืนไม่ได้ คัดลอกเป็นใบใหม่ได้จากหน้าออกเอกสาร (copy=1 รับใบที่ยกเลิกแล้ว) */
export function copyHrefFor(kind: string, id: string): string | null {
  return ['IV', 'IVT', 'RC'].includes(kind) ? `/income/new?kind=${kind}&from=${id}&copy=1` : null;
}
