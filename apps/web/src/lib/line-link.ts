/**
 * การผูกบรรทัดรายการกับทะเบียนสินค้า — กติกาที่ตัดสินว่าบรรทัดไหนจะขยับสต๊อก
 *
 * ทั้งฝั่งขายและฝั่งซื้อตัดสินด้วย `productId` ตัวเดียวกัน (sales.ts · purchases.ts):
 * บรรทัดที่ไม่มี `productId` จะถูกข้ามตอนตัด/รับของเข้าโดยไม่มีอะไรฟ้อง
 *
 * เดิมช่องรหัสในฟอร์มล้าง `productId` ทิ้งทุกตัวอักษรที่พิมพ์ และไม่มีทางกลับ —
 * เคาะเว้นวรรคแล้วลบ หรือแก้รหัสให้ตรงกับที่เขียนบนกล่องแล้วแก้กลับ ก็พอ
 * บรรทัดนั้นจะหน้าตาเหมือนเดิมทุกอย่าง บันทึกผ่าน พิมพ์บิลสวย แต่ไม่ตัดสต๊อกอีกเลย
 * (อู่แจ้งเข้ามา 21 ก.ย. 2569 — "ออกบิลใบเปล่าจ่ายสดแล้วของไม่ลด")
 *
 * ไฟล์นี้จึงแยกกติกาออกจากหน้าจอเพื่อให้ทดสอบได้ เหมือนที่ line-qty.ts ทำกับจำนวน
 */

/** รหัสของสินค้าที่บรรทัดเคยผูกไว้ — จำไว้เพื่อผูกคืนถ้าพิมพ์กลับมาเหมือนเดิม */
export interface CodeLink {
  id: string;
  code: string;
}

export interface CodeLine {
  productId: string | null;
  code: string;
}

/**
 * ผู้ใช้พิมพ์ในช่องรหัสของบรรทัด — คืน patch ที่จะลงบรรทัด กับความจำที่จะถือต่อ
 *
 *   บรรทัดที่ผูกทะเบียนอยู่ · พิมพ์แล้วได้รหัสเดิม → ไม่ถือว่าเปลี่ยน การผูกอยู่ครบ
 *   บรรทัดที่ผูกทะเบียนอยู่ · รหัสเปลี่ยนจริง      → ตัดการผูก แต่**จำรหัสเดิมไว้**
 *   บรรทัดที่หลุดไปแล้ว   · พิมพ์กลับมาตรงรหัสเดิม → ผูกคืนให้เอง
 *
 * ที่ต้องจำไว้เพราะ `line.code` ถูกทับด้วยสิ่งที่พิมพ์ไปแล้ว ตัวบรรทัดเองจึงตอบไม่ได้
 * ว่า "เดิมคือรหัสอะไร" — ถ้าไม่จำ การลบตัวอักษรกลับคืนก็ไม่ช่วยอะไร
 *
 * เลือกสินค้าจากผลค้นหาเมื่อไร ให้ทิ้งความจำ (`memo: null`) เพราะบรรทัดผูกตัวใหม่แล้ว
 */
export function typeCode<T extends CodeLine>(
  line: T,
  typed: string,
  memo: CodeLink | null,
): { patch: Partial<T>; memo: CodeLink | null } {
  const code = { code: typed } as Partial<T>;

  if (line.productId) {
    /* ไม่ได้เปลี่ยนอะไรจริง — เคาะแล้วลบ หรือพิมพ์ทับด้วยตัวเดิม */
    if (typed === line.code) return { patch: code, memo };
    /* รหัสว่างอยู่แล้วก็ไม่มีอะไรให้จำ ไม่งั้นพิมพ์ว่างทีหลังจะผูกคืนมั่ว */
    const next = line.code.trim() ? { id: line.productId, code: line.code } : memo;
    return { patch: { ...code, productId: null } as Partial<T>, memo: next };
  }

  if (memo && typed.trim() && typed === memo.code) {
    return { patch: { ...code, productId: memo.id } as Partial<T>, memo };
  }

  return { patch: code, memo };
}

export interface StockLine {
  productId: string | null;
  /** บรรทัดชุดอะไหล่ตัดสต๊อกที่ชิ้นส่วน ไม่ได้ผูก productId ของตัวเอง (ฝั่งขายเท่านั้น) */
  kitId?: string | null;
  /** ค่าแรง/ค่าบริการ ไม่มีของให้ตัดอยู่แล้ว ไม่ต้องเตือน (ฝั่งขายเท่านั้น) */
  isService?: boolean;
  qty: number;
}

/**
 * บรรทัดที่จะ**ไม่**ขยับสต๊อกตอนบันทึก — เอาไว้เตือนก่อนที่ของจะเพี้ยน
 *
 * เงื่อนไขตรงกับที่เซิร์ฟเวอร์ใช้ข้ามบรรทัด (`!it.productId || it.qty === 0`)
 * บวกกับที่ฝั่งขายยกเว้นให้: บรรทัดชุดอะไหล่ (ตัดที่ชิ้นส่วน) และค่าแรง (ไม่มีของ)
 *
 * บรรทัดจำนวน 0 ไม่นับว่าน่าเตือน — ไม่มีของจะขยับอยู่แล้ว ไม่ใช่ของหาย
 */
export function unstockedLines<T extends StockLine>(items: readonly T[]): T[] {
  return items.filter((it) => !it.productId && !it.kitId && !it.isService && it.qty !== 0);
}
