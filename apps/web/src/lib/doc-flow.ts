/**
 * กติกาของกระดานงานบนหน้ารายการใบเสนอราคา
 *
 * แยกออกมาจากคอมโพเนนต์เพราะการตัดสินใจว่าจะแสดงอะไรมีสี่ทาง ไม่ใช่สองทาง
 * และลำดับการตัดสินสำคัญ — ใบที่ออกแล้วต้องเห็นเลขที่เสมอ แม้ใบแม่จะถูกยกเลิก
 * ไปแล้วก็ตาม ไม่งั้นเอกสารภาษีที่ออกไปแล้วจะหายไปจากสายตาโดยที่มันยังมีผลอยู่
 */
export type TodoState =
  /** ออกใบต่อไปแล้ว — แสดงเลขที่ให้กดดู */
  | { kind: 'done' }
  /** ยังไม่ได้ออก และกดออกได้ */
  | { kind: 'todo' }
  /** ใบแม่ถูกยกเลิก ออกต่อไม่ได้ */
  | { kind: 'voided' }
  /** ผู้ใช้คนนี้ไม่มีสิทธิ์ออกเอกสารชนิดนั้น */
  | { kind: 'denied' };

export function todoState(opts: {
  /** ออกใบต่อไปแล้วหรือยัง — ใบที่ถูกยกเลิกไม่นับว่าออกแล้ว ต้องกรองมาก่อนถึงนี่ */
  done: boolean;
  /** ใบแม่ถูกยกเลิกแล้ว */
  sourceVoided: boolean;
  /** มีสิทธิ์ออกเอกสารชนิดที่จะออกต่อ */
  canMake: boolean;
}): TodoState {
  if (opts.done) return { kind: 'done' };
  if (opts.sourceVoided) return { kind: 'voided' };
  if (!opts.canMake) return { kind: 'denied' };
  return { kind: 'todo' };
}

/**
 * ชนิดเอกสารที่ควรตั้งต้นให้เมื่อกด "รอจัดทำ" จากใบเสนอราคา
 *
 * ใบส่งมอบตั้งต้นเป็นแบบมีใบกำกับภาษี ตามที่อู่ส่วนใหญ่ออก
 * ผู้ใช้สลับเป็นแบบไม่มี VAT ได้จากแถบชนิดบนหน้าออกเอกสาร
 * (รุ่น 6.4 ถามด้วยกล่องเลือกก่อน เราให้สลับทีหลังแทน ผลปลายทางเหมือนกัน)
 */
export function newDocHref(fromId: string, target: 'invoice' | 'receipt'): string {
  return `/income/new?kind=${target === 'invoice' ? 'IVT' : 'RC'}&from=${fromId}`;
}
