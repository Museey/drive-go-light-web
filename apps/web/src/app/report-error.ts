'use server';

import { headers } from 'next/headers';
import { recordError } from '@/lib/ops';
import { callerIp, RateLimiter } from '@/lib/rate-limit';

/**
 * เพดานของทางเข้านี้
 *
 * ผู้ใช้จริงคนหนึ่งเจอข้อผิดพลาดกี่ครั้งต่อนาที — หน้าที่พังยับก็ยังนับได้ด้วยนิ้วมือ
 * 20 จึงกว้างเกินพอสำหรับของจริง และแคบพอที่การยิงซ้ำจะไม่ไปถึงฐานข้อมูล
 *
 * ก้อนรวมมีไว้กันคนที่มีไอพีเยอะ — ต่อให้กระจายมาจากพันไอพี ก็ยังชนเพดานนี้อยู่ดี
 * ตั้งไว้สูงพอที่เหตุขัดข้องจริงของอู่ทุกรายพร้อมกันจะไม่ชน
 */
const PER_IP = new RateLimiter({ limit: 20, windowMs: 60_000, maxKeys: 5_000 });
const OVERALL = new RateLimiter({ limit: 300, windowMs: 60_000, maxKeys: 1 });

/**
 * รับข้อผิดพลาดจากฝั่งเบราว์เซอร์มาบันทึก
 *
 * ไม่ตรวจสิทธิ์ เพราะข้อผิดพลาดเกิดกับคนที่ยังไม่ได้ล็อกอินได้ (หน้าล็อกอินพังเอง)
 * แต่ recordError() ตัดข้อความยาวและกรองความลับให้แล้ว
 *
 * **ทางเข้าที่ไม่ต้องล็อกอิน + ปลายทางเขียนฐานข้อมูล = ต้องมีเพดานเสมอ**
 * เดิมไม่มี ใครก็ยิงซ้ำให้ตารางโตจนดิสก์เต็มได้ และดิสก์นั้นเป็นของทุกอู่ร่วมกัน
 * (ตรวจความปลอดภัย 24 ก.ย. 2569 · อีกชั้นคือการรวมแถวซ้ำใน db/035)
 *
 * เกินเพดานแล้ว **เงียบ ไม่โยน error** — ผู้เรียกคือตัวดักข้อผิดพลาดของหน้าเว็บ
 * ถ้าที่นี่โยนกลับไป หน้าที่พังอยู่แล้วจะพังซ้ำซ้อนจนผู้ใช้ไม่เหลืออะไรให้กดเลย
 */
export async function reportClientError(input: {
  message: string;
  stack: string | null;
  digest: string | null;
  path: string | null;
}): Promise<void> {
  /* อ่านไอพีไม่ได้ก็จัดเป็นก้อนเดียวกันทั้งหมด — แคบเกินไปดีกว่าปล่อยผ่านทั้งหมด */
  const ip = callerIp(await headers()) ?? 'unknown';

  if (!PER_IP.check(ip).ok) return;
  if (!OVERALL.check('all').ok) return;

  await recordError({ kind: 'client', ...input });
}
