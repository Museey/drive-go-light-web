/**
 * ปุ่มวิธีรับ/จ่ายชำระต้องบอกว่าตอนนี้เลือกอะไรอยู่ (ผู้ใช้แจ้ง 19 ก.ย. 2569)
 *
 * โหมดอ่านจากข้อมูลจริง ไม่ใช่จำว่าเพิ่งกดปุ่มไหน — กรอกยอดเองในช่องก็ต้องขยับตาม
 * ไม่งั้นปุ่มจะโกหกทันทีที่ผู้ใช้แก้ตัวเลข
 */
import { describe, expect, it } from 'vitest';
import { payModeOf } from '../src/lib/pay-mode';

const cash = (amount: number) => [{ method: 'เงินสด', amount }];
const transfer = (amount: number) => [{ method: 'เงินโอน', amount }];

describe('โหมดการรับชำระที่กำลังเลือกอยู่', () => {
  it('ไม่มีรายการรับชำระเลย = ยังไม่รับเงิน (เครดิต)', () => {
    expect(payModeOf([], 1000)).toBe('credit');
  });

  /* กดปุ่ม "ชำระบางส่วน" แล้วระบบเปิดแถวเงินสดยอด 0 ให้กรอก — ระหว่างพิมพ์ปุ่มต้องค้างที่บางส่วน
     ไม่ใช่เด้งไปติด "ยังไม่รับเงิน" ซึ่งผู้ใช้ไม่ได้เลือก */
  it('มีแถวรับชำระแต่ยอดยังเป็นศูนย์ = กำลังชำระบางส่วน', () => {
    expect(payModeOf(cash(0), 1000)).toBe('partial');
  });

  it('เงินสดเต็มยอด = เงินสดเต็มจำนวน · เงินโอนเต็มยอด = โอนเต็มจำนวน', () => {
    expect(payModeOf(cash(1000), 1000)).toBe('cash');
    expect(payModeOf(transfer(1000), 1000)).toBe('transfer');
  });

  it('รับไม่ครบ = ชำระบางส่วน ไม่ว่าจะช่องทางไหน', () => {
    expect(payModeOf(cash(400), 1000)).toBe('partial');
    expect(payModeOf(transfer(999.99), 1000)).toBe('partial');
  });

  it('รับหลายช่องทางรวมกันเต็ม ก็ยังเป็นชำระบางส่วน — ไม่มีปุ่มไหนตรง', () => {
    expect(payModeOf([{ method: 'เงินสด', amount: 600 }, { method: 'เงินโอน', amount: 400 }], 1000)).toBe('partial');
  });

  it('เศษสตางค์จากการปัด ไม่ทำให้ยอดเต็มกลายเป็นบางส่วน', () => {
    expect(payModeOf(cash(1000.004), 1000)).toBe('cash');
    expect(payModeOf(cash(999.999), 1000)).toBe('cash');
  });

  it('รับเกินยอด ยังนับเป็นเต็มจำนวนของช่องทางนั้น (ทอนเงินหน้าร้าน)', () => {
    expect(payModeOf(cash(1200), 1000)).toBe('cash');
  });

  it('ยอดที่ต้องชำระเป็นศูนย์ (ใบว่าง) และไม่มีแถวรับชำระ = ยังไม่รับเงิน', () => {
    expect(payModeOf([], 0)).toBe('credit');
  });
});
