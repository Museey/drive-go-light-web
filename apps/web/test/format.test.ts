/**
 * ตัวจัดรูปแบบวันที่และเวลา
 *
 * thDateTime ตรึงเขตเวลาไว้ที่เวลาไทยเสมอ ไม่ใช่เขตเวลาของเครื่องที่เปิดดู —
 * ถ้าปล่อยตามเครื่อง เจ้าของอู่ที่เปิดดูจากต่างประเทศจะเห็นเวลาบันทึกเอกสาร
 * ไม่ตรงกับที่พนักงานหน้าร้านเห็น แล้วเถียงกันว่าใครแก้ตอนไหน
 */
import { describe, expect, it } from 'vitest';
import { thDate, thDateLong, thDateTime } from '../src/lib/format';

describe('วันที่แบบไทย', () => {
  it('แปลง พ.ศ. และใช้ชื่อเดือนย่อ', () => {
    expect(thDate('2026-09-06')).toBe('6 ก.ย. 2569');
    expect(thDateLong('2026-01-31')).toBe('31 มกราคม 2569');
  });

  it('ค่าว่างได้ขีด ไม่ใช่ NaN', () => {
    expect(thDate(null)).toBe('-');
    expect(thDateTime(undefined)).toBe('-');
  });
});

describe('วันที่และเวลาแบบไทย', () => {
  it('แสดงตามเวลาไทยเสมอ ไม่ว่าเครื่องที่รันจะอยู่เขตเวลาไหน', () => {
    /* 17:05 UTC = 00:05 ของวันถัดไปตามเวลาไทย — ข้ามวันด้วย */
    expect(thDateTime('2026-09-06T17:05:00Z')).toBe('7 ก.ย. 2569 00:05 น.');
  });

  it('เวลาบ่ายไม่กลายเป็น 12 ชั่วโมง', () => {
    expect(thDateTime('2026-09-06T08:30:00Z')).toBe('6 ก.ย. 2569 15:30 น.');
  });

  it('เที่ยงคืนตามเวลาไทยเป็น 00 ไม่ใช่ 24', () => {
    expect(thDateTime('2026-09-05T17:00:00Z')).toBe('6 ก.ย. 2569 00:00 น.');
  });

  it('ข้ามปีตอนตีเจ็ดของวันสิ้นปีตามเวลา UTC', () => {
    /* 31 ธ.ค. 2026 18:00 UTC = 1 ม.ค. 2027 01:00 ไทย = พ.ศ. 2570 */
    expect(thDateTime('2026-12-31T18:00:00Z')).toBe('1 ม.ค. 2570 01:00 น.');
  });

  it('ค่าที่อ่านไม่ออก คืนค่าเดิม ไม่ใช่ Invalid Date', () => {
    expect(thDateTime('ไม่ใช่วันที่')).toBe('ไม่ใช่วันที่');
  });
});
