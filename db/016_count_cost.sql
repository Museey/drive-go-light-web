-- ใบตรวจนับเคยเก็บแค่ต้นทุน**ต่อหน่วย** แล้วให้หน้าจอคูณกับส่วนต่างเอง
-- ซึ่งไม่มีวันตรงกับเงินที่ถูกบันทึกเข้างบจริง เพราะของที่หายไปถูกตัดตามล็อต
-- แบบเข้าก่อนออกก่อน — หาย 15 ชิ้นอาจเป็น 10 ชิ้นที่ 100 บวก 5 ชิ้นที่ 150
-- ไม่ใช่ 15 ชิ้นที่ราคาเดียว และการหารกลับมาเป็นราคาต่อหน่วยก็ปัดเศษทิ้ง
--
-- เก็บ "เป็นเงิน" ที่ตัดจริงลงไปเลย หน้ารายการกับงบจะได้พูดตัวเลขเดียวกัน
-- ค่าเป็นบวกเสมอ เครื่องหมายอยู่ที่ส่วนต่าง (นับได้น้อยกว่าระบบ = เสียเงิน)
-- แบบเดียวกับ stock_moves.cost_amount
--
-- ว่างได้ — ใบที่ยังเป็นร่างยังไม่มีอะไรถูกตัด และใบเก่าที่ปรับไปก่อนหน้านี้
-- ไม่มีค่านี้ หน้าจอถอยไปคูณจากต้นทุนต่อหน่วยเหมือนเดิมสำหรับใบเหล่านั้น
