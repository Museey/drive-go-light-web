set local lock_timeout = '5s';

alter table stock_count_items add column if not exists cost_amount numeric(14,2);

alter table stock_count_items drop constraint if exists count_item_cost_positive;
alter table stock_count_items add constraint count_item_cost_positive
  check (cost_amount is null or cost_amount >= 0);
