-- **ปกติวิวใน Postgres ทำงานด้วยสิทธิ์ของ *เจ้าของวิว* ไม่ใช่ของคนที่เรียก**
-- เจ้าของคือใครก็ตามที่รัน create view ซึ่งคือ role ที่ใช้รันไมเกรชัน
--
-- ถ้าวันไหนไมเกรชันถูกรันด้วย role ที่ข้าม RLS ได้ (superuser หรือ BYPASSRLS)
-- วิวนี้จะอ่านข้ามอู่ได้ทันทีโดยไม่มีอาการให้เห็น — ตัวเลขที่ออกมายังดูสมเหตุสมผล
-- ผิดแค่ว่ามันรวมของอู่อื่นมาด้วย ซึ่งเป็นข้อผิดพลาดชนิดที่ไม่มีใครจับได้ด้วยตา
--
-- security_invoker บอกให้ประเมินด้วยสิทธิ์ของคนเรียกเสมอ **ถูกต้องไม่ว่าใครจะเป็น
-- เจ้าของ** จึงไม่ต้องไปพึ่งว่าใครรันไมเกรชันด้วย role ไหน ซึ่งเป็นเงื่อนไข
-- ที่เราควบคุมไม่ได้บนบริการ Postgres แบบ managed
--
-- (ต้องใช้ Postgres 15 ขึ้นไป — เครื่องจริงเป็น 16)
-- =====================================================================

set local lock_timeout = '5s';

alter view product_stock set (security_invoker = true);
