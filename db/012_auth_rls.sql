-- =====================================================================
-- DriveGoLight! Web — migration 012 · แก้ยืนยันตัวตนพังบนฐานที่เจ้าของไม่ใช่ superuser
--
-- **อาการ** เจ้าของอู่ล็อกอินไม่ได้เลย และลิงก์ตั้งรหัสผ่านขึ้นว่า "ลิงก์ใช้ไม่ได้แล้ว"
-- ตั้งแต่วินาทีแรกที่ออกลิงก์ — บนเครื่องพัฒนาไม่มีอาการ
--
-- **สาเหตุ** `force row level security` มีผลกับ **เจ้าของตาราง** ด้วย
-- ฟังก์ชันในสคีมา auth เป็น SECURITY DEFINER จึงทำงานในนามเจ้าของตาราง
-- และตั้งใจให้มองข้ามอู่ได้ เพราะตอนล็อกอินยังไม่รู้ว่าเป็นอู่ไหน
--   auth.find_user_for_signin(email)   หาผู้ใช้จากอีเมล ข้ามทุกอู่
--   auth.peek_setup_token(hash)        เปิดลิงก์ตั้งรหัสผ่านโดยยังไม่ได้ล็อกอิน
-- ทั้งสองตัว join users กับ tenants ซึ่งโดน RLS กรองจนไม่เหลือแถว
--
-- ที่ไม่เจอตอนพัฒนา เพราะฐานทดสอบมีเจ้าของเป็น postgres ซึ่งเป็น superuser
-- และ superuser ข้าม RLS ได้เองอยู่แล้ว ส่วนบริการ Postgres แบบ managed
-- ให้ role ที่ **ไม่ใช่** superuser มาเป็นเจ้าของ
--
-- **ทางแก้** ปิด force เฉพาะ users กับ tenants
--
-- force มีไว้บังคับ RLS กับ *เจ้าของตาราง* เท่านั้น — role ที่ไม่ใช่เจ้าของ
-- (ซึ่งก็คือ dgl_app ที่แอปใช้ต่อ) ยังโดน RLS กรองเต็มที่เหมือนเดิมทุกประการ
-- **การแยกข้อมูลของอู่ที่หน้านโยบายข้อมูลส่วนบุคคลสัญญาไว้จึงไม่เปลี่ยน**
-- มีเทสต์ยืนยันว่า dgl_app ยังอ่านข้ามอู่ไม่ได้ทั้งสองตาราง
--
-- ตารางข้อมูลธุรกิจ (documents · contacts · products · doc_items · payments
-- และที่เหลือทั้งหมด) **ยังคง force ไว้เหมือนเดิม** เพราะไม่มีฟังก์ชันไหน
-- ต้องอ่านข้ามอู่ ถ้าวันหนึ่งมี ให้คิดใหม่ อย่าปิด force เพิ่มโดยอัตโนมัติ
--
-- สิ่งที่แลกไป — ฟังก์ชัน SECURITY DEFINER ที่เป็นของเจ้าของตาราง อ่าน users
-- กับ tenants ข้ามอู่ได้โดยไม่มี RLS กั้น ซึ่งเป็นสิ่งที่ auth ต้องใช้พอดี
-- ชั้นที่มาแทนคือ **แอปต้องไม่ต่อฐานด้วย role ที่เป็นเจ้าของตาราง**
-- ซึ่งบังคับไว้ที่ assertRlsEnforced() ใน apps/web/src/lib/db.ts แล้ว
-- =====================================================================

set local lock_timeout = '5s';

alter table users   no force row level security;
alter table tenants no force row level security;

comment on table users is
  'ปิด force row level security ไว้โดยตั้งใจ — ฟังก์ชัน auth.* ต้องหาผู้ใช้จากอีเมล '
  'ข้ามทุกอู่ตอนล็อกอิน ดู db/012_auth_rls.sql · role ที่ไม่ใช่เจ้าของตารางยังโดน RLS กรองปกติ';

comment on table tenants is
  'ปิด force row level security ไว้โดยตั้งใจ — เหตุผลเดียวกับ users ดู db/012_auth_rls.sql';
